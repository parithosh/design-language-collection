// ---- Contrast -----------------------------------------------------------

function expandRef(ref) {
  const m = /^ansi:(\d+)(?:-(\d+))?$/.exec(ref);
  if (!m) return [ref];
  const from = Number(m[1]), to = Number(m[2] ?? m[1]);
  return Array.from({ length: to - from + 1 }, (_, i) => `ansi:${from + i}`);
}

function contrastReport() {
  const rows = [];
  const add = (theme, variant, lookup, pairs) => {
    for (const [fgRef, bgRef, min] of pairs) {
      for (const fg of expandRef(fgRef)) {
        const fgHex = lookup(fg), bgHex = lookup(bgRef);
        if (!fgHex || !bgHex) throw new Error(`${theme}/${variant}: unknown token in pair ${fg} on ${bgRef}`);
        const ratio = Math.floor(contrastHex(fgHex, bgHex) * 100) / 100;
        rows.push({ theme, variant, fg, bg: bgRef, fgHex, bgHex, ratio, min, pass: contrastHex(fgHex, bgHex) >= min });
      }
    }
  };
  for (const mode of MODES) {
    const m = stone.modes[mode];
    add("stone", mode, (r) => (r.startsWith("ansi:") ? m.ansi[Number(r.slice(5))] : m.color[r]), stone.contrast);
  }
  for (const f of pallu.fabrics) {
    const t = Object.fromEntries(palluTokens[f.id].tokens);
    add("pallu", f.id, (r) => (r.startsWith("#") ? r : t[r]), pallu.contrast);
  }
  return rows;
}

