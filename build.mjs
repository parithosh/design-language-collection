#!/usr/bin/env node
// Generates every file in dist/ from tokens/*.json.
//
//   node build.mjs           write dist/
//   node build.mjs --check   fail if dist/ is stale or any contrast pair fails
//   node build.mjs --site    write dist/, then stage the showcase in _site/
//
// No dependencies: Node 20+ only.

import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { contrastHex, parseHex, resolve, toHex } from "./lib/pallu.mjs";

const ROOT = dirname(fileURLToPath(import.meta.url));
const read = (p) => JSON.parse(readFileSync(join(ROOT, p), "utf8"));
const base = read("tokens/base.json");
const stone = read("tokens/stone.json");
const pallu = read("tokens/pallu.json");

const HEADER = "Generated by build.mjs from tokens/. Do not edit by hand.";
const FONT_URL = "../../assets/fonts/";

// ---- small helpers ------------------------------------------------------

const json = (v) => JSON.stringify(v, null, 2) + "\n";
const entries = (o) => Object.entries(o).filter(([k]) => !k.startsWith("$"));

/** Mix two hex colours in sRGB; t = share of b. */
function mix(a, b, t) {
  const x = parseHex(a), y = parseHex(b);
  return toHex({ r: x.r + (y.r - x.r) * t, g: x.g + (y.g - x.g) * t, b: x.b + (y.b - x.b) * t });
}

function fontFaces(faces) {
  return faces
    .map(({ family, weight, style, files }) =>
      files
        .map(
          (f) =>
            `@font-face {\n  font-family: "${family}";\n  font-style: ${style};\n  font-weight: ${weight};\n  font-display: swap;\n  src: url("${FONT_URL}${f}") format("woff2");${
              f.includes("latin-ext") ? "\n  unicode-range: U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF;" : ""
            }\n}`,
        )
        .join("\n"),
    )
    .join("\n");
}

/** Shared scales as [name, value] pairs, e.g. ["space-4", "16px"]. */
const baseVars = () =>
  entries(base).flatMap(([group, scale]) => entries(scale).map(([k, v]) => [`${group}-${k}`, v]));

const decls = (pairs, indent = "  ") => pairs.map(([k, v]) => `${indent}--${k}: ${v};`).join("\n");

// ---- Stone --------------------------------------------------------------

const MODES = ["light", "dark"];

/** Resolve a syntax role ("ansi:6" or a colour token) for one mode. */
const syntaxColor = (mode, ref) =>
  ref.startsWith("ansi:") ? stone.modes[mode].ansi[Number(ref.slice(5))] : stone.modes[mode].color[ref];

const stoneSyntax = (mode) => Object.fromEntries(entries(stone.syntax).map(([role, ref]) => [role, syntaxColor(mode, ref)]));

function stoneModeVars(mode) {
  const m = stone.modes[mode];
  return [
    ...entries(m.color),
    ...m.ansi.map((c, i) => [`ansi-${i}`, c]),
    ...entries(stoneSyntax(mode)).map(([k, v]) => [`syntax-${k}`, v]),
  ];
}

function stoneThemeVars() {
  return [
    ...entries(stone.font).map(([k, v]) => [`font-${k}`, v]),
    ...entries(stone.radius).map(([k, v]) => [`radius-${k}`, v]),
    ...entries(stone.shadow).map(([k, v]) => [`shadow-${k}`, v]),
  ];
}

function stoneCss() {
  return `/* Stone: ${stone.modes.light.name} (light) and ${stone.modes.dark.name} (dark). ${HEADER}
 * Follows the OS setting; force a mode with <html data-mode="light"> or data-mode="dark". */

${fontFaces(stone.fontFaces)}

:root {
  color-scheme: light dark;
${decls(baseVars())}
${decls(stoneThemeVars())}
${decls(stoneModeVars("light"))}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-mode="light"]) {
${decls(stoneModeVars("dark"), "    ")}
  }
}

[data-mode="light"] {
  color-scheme: light;
${decls(stoneModeVars("light"))}
}

[data-mode="dark"] {
  color-scheme: dark;
${decls(stoneModeVars("dark"))}
}
`;
}

// ---- Pallu --------------------------------------------------------------

const palluTokens = Object.fromEntries(pallu.fabrics.map((f) => [f.id, resolve(pallu, { fabric: f.id })]));

function palluCss() {
  const [rani, ...others] = pallu.fabrics;
  const fixed = [
    ["font-display", pallu.font.display],
    ["font-read", pallu.font.body],
    ["font-body", pallu.font.body],
    ["font-ui", pallu.font.ui],
    ["font-mono", pallu.font.mono],
    ["pl-radius", pallu.radius.md],
    ["pl-radius-chip", pallu.radius.sm],
    ...entries(pallu.radius).map(([k, v]) => [`radius-${k}`, v]),
  ];
  const shared = entries(pallu.shared).map(([k, v]) => [k, `var(--${v})`]);
  return `/* Pallu: the saree-woven identity from piecesoflife. ${HEADER}
 * Light only. ${rani.name} is the default; switch fabric with data-fabric="${others.map((f) => f.id).join('|')}"
 * on <html> or any element. Pallu's own names (--rani, --marigold, ...) and the family's shared
 * names (--brand, --accent, ...) both work. */

${fontFaces(pallu.fontFaces)}

:root {
  color-scheme: light;
${decls(baseVars())}
${decls(fixed)}
${decls(palluTokens.rani.tokens)}
}

/* Shared names resolve wherever a fabric is set, so they follow it. */
:root,
[data-fabric] {
${decls(shared)}
}
${others
  .map(
    (f) => `
/* ${f.name}: ${f.vibe} */
[data-fabric="${f.id}"] {
${decls(palluTokens[f.id].tokens)}
}`,
  )
  .join("\n")}
`;
}

// ---- Tailwind v4 --------------------------------------------------------

// Colours reference the live variables so modes and fabrics keep working.
// Everything else is written out literally: those names share Tailwind's
// namespaces (--font-*, --text-*, --radius-*, ...), so Tailwind must emit
// the same values the theme does.
const SHARED = Object.keys(stone.modes.light.color);

function tailwindCss(theme, literal) {
  return `/* Tailwind v4 theme for ${theme}. ${HEADER}
 * Usage: @import "tailwindcss"; @import "<path>/dist/tailwind/${theme.toLowerCase()}.css"; */

@import "../css/${theme.toLowerCase()}.css";

@theme inline {
${SHARED.map((n) => `  --color-${n}: var(--${n});`).join("\n")}
}

@theme {
${decls(literal)}
}
`;
}

const tailwindLiterals = (fonts, radius) => [
  ...entries(fonts).map(([k, v]) => [`font-${k}`, v]),
  ...entries(radius).map(([k, v]) => [`radius-${k}`, v]),
  ...entries(base.text).map(([k, v]) => [`text-${k}`, v]),
  ...entries(base.leading).map(([k, v]) => [`leading-${k}`, v]),
  ...entries(base.tracking).map(([k, v]) => [`tracking-${k}`, v]),
];

// ---- JSON ---------------------------------------------------------------

function stoneJson() {
  return {
    $comment: HEADER,
    name: stone.name,
    modes: Object.fromEntries(
      MODES.map((m) => [m, { name: stone.modes[m].name, color: stone.modes[m].color, ansi: stone.modes[m].ansi, syntax: stoneSyntax(m) }]),
    ),
    font: stone.font,
    radius: stone.radius,
    base: Object.fromEntries(entries(base)),
  };
}

function palluJson() {
  return {
    $comment: HEADER,
    name: pallu.name,
    fabrics: Object.fromEntries(
      pallu.fabrics.map((f) => {
        const t = Object.fromEntries(palluTokens[f.id].tokens);
        return [f.id, { name: f.name, vibe: f.vibe, tokens: t, shared: Object.fromEntries(entries(pallu.shared).map(([k, v]) => [k, t[v]])) }];
      }),
    ),
    font: pallu.font,
    radius: pallu.radius,
    base: Object.fromEntries(entries(base)),
  };
}

