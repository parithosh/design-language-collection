// Pallu invariants carried over from piecesoflife's theme tests.
function palluInvariants() {
  const errors = [];
  const rani = Object.fromEntries(palluTokens.rani.tokens);
  const reference = { ...Object.fromEntries(Object.entries(pallu.seedTokens).map(([seed, tok]) => [tok, pallu.fabrics[0][seed]])), ...Object.fromEntries(pallu.derived.map(([n, , v]) => [n, v])) };
  for (const [name, want] of Object.entries(reference)) {
    if (rani[name] !== want) errors.push(`pallu: Rani's --${name} is ${rani[name]}, pallu.css has ${want}`);
  }
  for (const f of pallu.fabrics) {
    const t = Object.fromEntries(palluTokens[f.id].tokens);
    for (const [seed, tok] of Object.entries(pallu.seedTokens)) {
      if (t[tok] !== f[seed]) errors.push(`pallu: fabric ${f.id} needed its ${seed} seed adjusted (${f[seed]} → ${t[tok]})`);
    }
  }
  return errors;
}

function listFiles(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? listFiles(p) : [p];
  });
}

const args = new Set(process.argv.slice(2));
const files = outputs();

if (args.has("--check")) {
  const errors = [];
  for (const [path, content] of Object.entries(files)) {
    const abs = join(ROOT, path);
    if (!existsSync(abs)) errors.push(`missing: ${path}`);
    else if (readFileSync(abs, "utf8") !== content) errors.push(`stale: ${path}`);
  }
  for (const abs of listFiles(join(ROOT, "dist"))) {
    const rel = relative(ROOT, abs);
    if (!(rel in files)) errors.push(`unexpected: ${rel}`);
  }
  const pairs = JSON.parse(files["dist/json/contrast.json"]).pairs;
  for (const p of pairs.filter((p) => !p.pass)) {
    errors.push(`contrast: ${p.theme}/${p.variant} ${p.fg} (${p.fgHex}) on ${p.bg} (${p.bgHex}) is ${p.ratio}:1, needs ${p.min}:1`);
  }
  errors.push(...palluInvariants());
  if (errors.length) {
    console.error(errors.join("\n"));
    console.error(`\nfail: ${errors.length} problem(s). Run \`node build.mjs\` to regenerate dist/.`);
    process.exit(1);
  }
  console.log(`ok: ${Object.keys(files).length} generated files are current, ${pairs.length} contrast pairs pass, Pallu fabrics resolve unadjusted`);
} else {
  rmSync(join(ROOT, "dist"), { recursive: true, force: true });
  for (const [path, content] of Object.entries(files)) {
    mkdirSync(dirname(join(ROOT, path)), { recursive: true });
    writeFileSync(join(ROOT, path), content);
  }
  console.log(`wrote ${Object.keys(files).length} files to dist/`);
  const problems = palluInvariants();
  if (problems.length) console.warn(problems.join("\n"));

  if (args.has("--site")) {
    const out = join(ROOT, "_site");
    rmSync(out, { recursive: true, force: true });
    cpSync(join(ROOT, "site"), out, { recursive: true });
    for (const dir of ["dist", "assets", "lib", "tokens"]) cpSync(join(ROOT, dir), join(out, dir), { recursive: true });
    console.log("staged the showcase in _site/");
  }
}
